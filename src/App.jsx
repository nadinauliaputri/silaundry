import React, { useState, useEffect } from 'react';
import Sidebar from './components/Sidebar';
import Header from './components/Header';
import ReceiptModal from './components/ReceiptModal';
import PasswordModal from './components/PasswordModal';
import NewTransactionModal from './components/NewTransactionModal';
import LogoutModal from './components/LogoutModal';
import TambahLayanan from './components/TambahLayanan';
import Toast from './components/Toast';

import LandingPage from './pages/LandingPage';
import Login from './pages/Login';
import RegisterToko from './pages/RegisterToko';
import Dashboard from './pages/Dashboard';
import Transaksi from './pages/Transaksi';
import Pelanggan from './pages/Pelanggan';
import Laporan from './pages/Laporan';
import Pendapatan from './pages/Pendapatan';
import ProfilAdmin from './pages/ProfilAdmin';

import { supabase } from './lib/supabaseClient';
import { WashingMachine, Shirt, CloudRain, Layers } from 'lucide-react';

export default function App() {
  const [activePage, setActivePage] = useState('landing');
  const [transactions, setTransactions] = useState([]);
  const [customers, setCustomers] = useState([]);
  const [adminProfile, setAdminProfile] = useState(null);
  const [servicesList, setServicesList] = useState([]); // will be loaded from Supabase

  // Modals state
  const [selectedReceiptTrx, setSelectedReceiptTrx] = useState(null);
  const [isPasswordModalOpen, setIsPasswordModalOpen] = useState(false);
  const [isNewTrxModalOpen, setIsNewTrxModalOpen] = useState(false);
  const [isLogoutModalOpen, setIsLogoutModalOpen] = useState(false);
  const [isMobileOpen, setIsMobileOpen] = useState(false);

// Services will be fetched from Supabase; initial empty array defined above
  const [isServiceModalOpen, setIsServiceModalOpen] = useState(false);
  const [editingService, setEditingService] = useState(null);

  // Dark mode state dengan persistensi localStorage & update class 'dark' di root HTML
  const [isDarkMode, setIsDarkMode] = useState(() => {
    if (typeof window !== 'undefined') {
      const saved = localStorage.getItem('silaundry_theme');
      if (saved) return saved === 'dark';
      return window.matchMedia('(prefers-color-scheme: dark)').matches;
    }
    return false;
  });

  useEffect(() => {
    if (isDarkMode) {
      document.documentElement.classList.add('dark');
      localStorage.setItem('silaundry_theme', 'dark');
    } else {
      document.documentElement.classList.remove('dark');
      localStorage.setItem('silaundry_theme', 'light');
    }
  }, [isDarkMode]);

  // Fetch initial data from Supabase (services, customers, transactions) on mount
  useEffect(() => {
    const fetchData = async () => {
      try {
        const { data: svcData, error: svcErr } = await supabase
          .from('services')
          .select('*')
          .order('id', { ascending: true });
        if (svcErr) {
          console.error('Error fetching services:', svcErr);
        } else if (svcData) {
          setServicesList(svcData);
        }

        const { data: custData, error: custErr } = await supabase.from('customers').select('*');
        if (custErr) {
          console.error('Error fetching customers:', custErr);
        } else if (custData) {
          setCustomers(custData);
        }

        const { data: trxData, error: trxErr } = await supabase.from('transactions').select('*');
        if (trxErr) {
          console.error('Error fetching transactions:', trxErr);
        } else if (trxData) {
          setTransactions(trxData);
        }
      } catch (err) {
        console.error('Error fetching initial data:', err);
      }
    };
    fetchData();
  }, []);

  const toggleDarkMode = () => {
    setIsDarkMode(prev => !prev);
  };

  // Toast notification
  const [toast, setToast] = useState(null);

  const showToast = (message, type = 'success') => {
    setToast({ message, type });
    setTimeout(() => {
      setToast(null);
    }, 3500);
  };

  // Handle Logout — redirect to landing page
  const handleLogout = () => {
    setIsLogoutModalOpen(false);
    setIsMobileOpen(false);
    setActivePage('landing');
    showToast('Anda berhasil keluar dari akun admin.', 'success');
  };

  // Fungsi generator ID Nota otomatis: SL-01, SL-02, dst., otomatis jadi 3 digit (SL-100) saat >= 100
  const generateNotaId = () => {
    const nextNum = transactions.length + 1;
    const formattedNum = nextNum < 100 ? String(nextNum).padStart(2, '0') : String(nextNum);
    return `SL-${formattedNum}`;
  };

  // Add new transaction and persist to Supabase
  const handleCreateTransaction = async (newTrxData) => {
    const generatedNota = generateNotaId();
    const newTrx = {
      ...newTrxData,
      nota: generatedNota,
      // id will be generated by Supabase if using UUID; fallback to timestamp
    };
    try {
      // Insert transaction
      const { data: insertedTrx, error: trxError } = await supabase.from('transactions').insert([newTrx]).single();
      if (trxError) throw trxError;
      // Upsert customer (create if not exists)
      const { data: existingCust } = await supabase.from('customers')
        .select('*')
        .eq('nama', newTrx.pelanggan)
        .single();
      if (existingCust) {
        const updatedCust = {
          ...existingCust,
          totalTransaksi: (existingCust.totalTransaksi || 0) + 1,
          totalPengeluaran: (existingCust.totalPengeluaran || 0) + newTrx.total,
          terakhirLaundry: 'Hari ini',
          riwayat: [
            { nota: insertedTrx.nota, tanggal: 'Hari ini', total: insertedTrx.total, status: insertedTrx.statusLaundry },
            ...(existingCust.riwayat || [])
          ]
        };
        await supabase.from('customers').update(updatedCust).eq('id', existingCust.id);
        setCustomers(prev => prev.map(c => c.id === existingCust.id ? updatedCust : c));
      } else {
        const newCustomerObj = {
          nama: newTrx.pelanggan,
          telepon: newTrx.telepon,
          alamat: newTrx.alamat || 'Surabaya',
          totalTransaksi: 1,
          totalPengeluaran: newTrx.total,
          terakhirLaundry: 'Hari ini',
          kategoriFavorit: newTrx.layanan,
          statusMember: 'Pelanggan Baru',
          riwayat: [{ nota: insertedTrx.nota, tanggal: 'Hari ini', total: insertedTrx.total, status: insertedTrx.statusLaundry }]
        };
        const { data: insertedCust } = await supabase.from('customers').insert([newCustomerObj]).single();
        setCustomers(prev => [insertedCust, ...prev]);
      }
      // Refresh transactions list
      const { data: refreshedTx } = await supabase.from('transactions').select('*');
      setTransactions(refreshedTx);
      showToast(`Pesanan nota ${insertedTrx.nota} (${insertedTrx.pelanggan}) berhasil ditambahkan!`);
      console.log('Transaction inserted:', insertedTrx);
      alert('Transaksi berhasil ditambahkan!');
      setSelectedReceiptTrx(insertedTrx);
    } catch (err) {
      console.error(err);
      alert('Gagal menambahkan transaksi.');
      alert('Gagal menambahkan transaksi.');
      showToast('Gagal menambahkan transaksi.', 'error');
    }
  };

  // Update transaction status laundry in Supabase
  const handleUpdateStatus = async (trxId, newStatus) => {
    try {
      const { error } = await supabase.from('transactions').update({ statusLaundry: newStatus }).eq('id', trxId);
      if (error) throw error;
      setTransactions(prev => prev.map(t => t.id === trxId ? { ...t, statusLaundry: newStatus } : t));
      showToast(`Status transaksi berhasil diubah menjadi "${newStatus}"`);
    } catch (err) {
      console.error(err);
      showToast('Gagal mengubah status transaksi.', 'error');
    }
  };

  // Update transaction payment status (Lunas / Belum Bayar) in Supabase
  const handleUpdatePayment = async (trxId, newPaymentStatus) => {
    try {
      const { error } = await supabase.from('transactions').update({ statusBayar: newPaymentStatus }).eq('id', trxId);
      if (error) throw error;
      setTransactions(prev => prev.map(t => t.id === trxId ? { ...t, statusBayar: newPaymentStatus } : t));
      showToast(`Status pembayaran berhasil diubah menjadi "${newPaymentStatus}"`);
    } catch (err) {
      console.error(err);
      showToast('Gagal mengubah status pembayaran.', 'error');
    }
  };

  if (activePage === 'landing') {
    return (
      <>
        <LandingPage
          onEnterLogin={() => setActivePage('login')}
          onOpenRegister={() => setActivePage('register')}
        />
        <Toast toast={toast} onClose={() => setToast(null)} />
      </>
    );
  }

  if (activePage === 'login') {
    return (
      <>
        <Login
          onBackToLanding={() => setActivePage('landing')}
          onLogin={async ({ email, password }) => {
            try {
              // Langkah 1: Login menggunakan Supabase Auth
              const { data: authData, error: authError } = await supabase.auth.signInWithPassword({
                email,
                password,
              });

              if (authError) {
                console.error('Auth login error:', authError);
                return { error: 'Email atau kata sandi salah. Silakan coba lagi.' };
              }

              if (!authData?.user) {
                return { error: 'Login gagal. Silakan coba lagi.' };
              }

              const authUserId = authData.user.id;
              console.log('Login berhasil, auth user id:', authUserId);

              // Langkah 2: Ambil data profil dari tabel profiles berdasarkan auth user id
              const { data: profileData, error: profileError } = await supabase
                .from('profiles')
                .select('*')
                .eq('id', authUserId)
                .single();

              if (profileError || !profileData) {
                console.error('Gagal mengambil profil:', profileError);
                return { error: 'Akun ditemukan tapi profil toko tidak tersedia.' };
              }

              // Simpan profileId ke localStorage
              localStorage.setItem('profileId', authUserId);

              // Set adminProfile dari data Supabase
              setAdminProfile({
                namaToko: profileData.nama_toko || 'SI LAUNDRY',
                namaAdmin: profileData.nama_admin || 'Admin',
                email: profileData.email || email,
                whatsapp: profileData.no_whatsapp || '',
                alamatToko: profileData.alamat || '',
                jamOperasional: profileData.jam_operasional || '',
              });

              setActivePage('dashboard');
              showToast(`Selamat datang kembali, ${profileData.nama_admin || 'Admin'}! 👋`);
              return {};
            } catch (err) {
              console.error('Login error:', err);
              return { error: 'Terjadi kesalahan saat login. Silakan coba lagi.' };
            }
          }}
          onOpenRegister={() => setActivePage('register')}
          adminProfile={adminProfile}
        />
        <Toast toast={toast} onClose={() => setToast(null)} />
      </>
    );
  }

  if (activePage === 'register') {
    return (
      <>
        <RegisterToko
          onBackToLanding={() => setActivePage('landing')}
          onEnterDashboard={() => setActivePage('dashboard')}
          onOpenLogin={() => setActivePage('login')}
          onRegisterSuccess={(newStoreData) => {
            setAdminProfile(prev => ({
              ...prev,
              namaToko: newStoreData.namaToko,
              namaAdmin: newStoreData.namaAdmin,
              email: newStoreData.email,
              whatsapp: newStoreData.whatsapp,
            }));
            showToast(`Toko "${newStoreData.namaToko}" berhasil didaftarkan! Selamat datang, ${newStoreData.namaAdmin}!`);
          }}
        />
        <Toast toast={toast} onClose={() => setToast(null)} />
      </>
    );
  }

  // Handlers Manajemen Layanan di Root Level
  const handleOpenAddService = () => {
    setEditingService(null);
    setIsServiceModalOpen(true);
  };

  const handleOpenEditService = (service) => {
    setEditingService(service);
    setIsServiceModalOpen(true);
  };

  const handleSaveService = async (savedData) => {
    if (editingService) {
      // Update existing service in Supabase
      try {
        const updates = {
          name: savedData.nama,
          price: Number(savedData.harga),
          unit: savedData.satuan,
          estimation: `Estimasi pengerjaan ${savedData.estimasi} hari`,
          status: savedData.status
        };
        const { error } = await supabase
          .from('services')
          .update(updates)
          .eq('id', editingService.id);

        if (error) throw error;
        console.log('Service updated:', updates);
        alert('Layanan berhasil diperbarui!');

        setServicesList(prev => prev.map(item => item.id === editingService.id ? { ...item, ...updates } : item));
        showToast(`Layanan "${savedData.nama}" berhasil diperbarui!`, 'success');
      } catch (err) {
        console.error('Error updating service:', err);
        alert(`Gagal memperbarui layanan: ${err.message || 'Terjadi kesalahan'}`);
        showToast('Gagal memperbarui layanan.', 'error');
      }
    } else {
      // Insert new service into Supabase
      const lower = (savedData.nama || '').toLowerCase();
      let bg_color = 'bg-[#E6F8F5]';
      let text_color = 'text-[#008A7B]';

      if (lower.includes('setrika') || lower.includes('baju') || lower.includes('kaos')) {
        bg_color = 'bg-[#EFEBF8]';
        text_color = 'text-[#6C5CE7]';
      } else if (lower.includes('selimut') || lower.includes('bedcover') || lower.includes('sprei') || lower.includes('gorden')) {
        bg_color = 'bg-[#FEF3E2]';
        text_color = 'text-[#D35400]';
      } else if (lower.includes('sepatu') || lower.includes('tas') || lower.includes('helm') || lower.includes('karpet')) {
        bg_color = 'bg-[#E0F2FE]';
        text_color = 'text-[#0284C7]';
      }

      const newObj = {
        name: savedData.nama,
        estimation: `Estimasi pengerjaan ${savedData.estimasi} hari`,
        price: Number(savedData.harga),
        unit: savedData.satuan,
        status: savedData.status,
        bg_color,
        text_color
      };

      try {
        const { data: inserted, error } = await supabase
          .from('services')
          .insert([newObj])
          .select()
          .single();

        if (error) throw error;
        console.log('Service inserted:', inserted);
        alert('Layanan berhasil ditambahkan!');

        setServicesList(prev => [...prev, inserted]);
        showToast(`Layanan "${savedData.nama}" berhasil ditambahkan ke katalog!`, 'success');
      } catch (err) {
        console.error('Error inserting service:', err);
        alert(`Gagal menambahkan layanan: ${err.message || 'Terjadi kesalahan'}`);
        showToast('Gagal menambahkan layanan.', 'error');
      }
    }
    setEditingService(null);
    setIsServiceModalOpen(false);
  };

  const handleDeleteService = async (serviceObjOrId) => {
    const targetId = typeof serviceObjOrId === 'object' ? serviceObjOrId.id : serviceObjOrId;
    try {
      const { error } = await supabase.from('services').delete().eq('id', targetId);
      if (error) throw error;
      console.log('Service deleted:', targetId);
      alert('Layanan berhasil dihapus!');
      setServicesList(prev => prev.filter(item => item.id !== targetId));
      showToast('Layanan berhasil dihapus dari katalog!', 'success');
    } catch (err) {
      console.error('Error deleting service:', err);
      alert(`Gagal menghapus layanan: ${err.message || 'Terjadi kesalahan'}`);
      showToast('Gagal menghapus layanan.', 'error');
    }
    setIsServiceModalOpen(false);
    setEditingService(null);
  };

  // Render Dashboard Pages Content
  const renderContent = () => {
    switch (activePage) {
      case 'dashboard':
        return (
          <Dashboard
            transactions={transactions}
            onSelectReceipt={(trx) => setSelectedReceiptTrx(trx)}
            onOpenNewTransaction={() => setIsNewTrxModalOpen(true)}
            servicesList={servicesList}
            onOpenAddService={handleOpenAddService}
            onOpenEditService={handleOpenEditService}
          />
        );
      case 'transaksi':
        return (
          <Transaksi
            transactions={transactions}
            onUpdateStatus={handleUpdateStatus}
            onUpdatePayment={handleUpdatePayment}
            onSelectReceipt={(trx) => setSelectedReceiptTrx(trx)}
            onOpenNewTransaction={() => setIsNewTrxModalOpen(true)}
          />
        );
      case 'pelanggan':
        return (
          <Pelanggan
            customers={customers}
            transactions={transactions}
            onSelectReceipt={(trx) => setSelectedReceiptTrx(trx)}
            onOpenNewTransaction={() => setIsNewTrxModalOpen(true)}
          />
        );
      case 'laporan':
        return (
          <Laporan
            transactions={transactions}
            onSelectReceipt={(trx) => setSelectedReceiptTrx(trx)}
            onShowToast={showToast}
          />
        );
      case 'pendapatan':
        return (
          <Pendapatan
            onShowToast={showToast}
          />
        );
      case 'profil':
        return (
          <ProfilAdmin
            adminProfile={adminProfile}
            onUpdateProfile={(updated) => setAdminProfile(updated)}
            onOpenPasswordModal={() => setIsPasswordModalOpen(true)}
            onShowToast={showToast}
          />
        );
      default:
        return (
          <Dashboard
            transactions={transactions}
            onSelectReceipt={(trx) => setSelectedReceiptTrx(trx)}
            onOpenNewTransaction={() => setIsNewTrxModalOpen(true)}
            servicesList={servicesList}
            onOpenAddService={handleOpenAddService}
            onOpenEditService={handleOpenEditService}
          />
        );
    }
  };

  const inProgressCount = transactions.filter(t => t.statusLaundry === 'Dalam pengerjaan').length;

  return (
    <div className={`min-h-screen ${isDarkMode ? 'dark bg-[#0B131E] text-slate-100' : 'bg-[#F5F7FA] text-[#1E293B]'} flex relative transition-colors duration-300`}>
      {/* Sidebar Navigation */}
      <Sidebar
        activePage={activePage}
        setActivePage={setActivePage}
        adminProfile={adminProfile}
        isMobileOpen={isMobileOpen}
        setIsMobileOpen={setIsMobileOpen}
        pendingCount={inProgressCount}
        onLogout={() => setIsLogoutModalOpen(true)}
      />

      {/* Main Content Area */}
      <div className="flex-1 flex flex-col min-w-0 lg:pl-64 transition-all">
        {/* Sticky Header */}
        <Header
          activePage={activePage}
          setIsMobileOpen={setIsMobileOpen}
          adminProfile={adminProfile}
          onOpenProfile={() => setActivePage('profil')}
          isDarkMode={isDarkMode}
          onToggleDarkMode={toggleDarkMode}
        />

        {/* Page Container */}
        <main className="flex-1 p-4 sm:p-6 lg:p-8 max-w-7xl w-full mx-auto">
          {renderContent()}
        </main>
      </div>

      {/* Global Modals & Notifications */}
      <ReceiptModal
        isOpen={Boolean(selectedReceiptTrx)}
        transaction={selectedReceiptTrx}
        onClose={() => setSelectedReceiptTrx(null)}
      />

      <PasswordModal
        isOpen={isPasswordModalOpen}
        onClose={() => setIsPasswordModalOpen(false)}
        onPasswordChanged={(msg) => showToast(msg, 'success')}
      />

      <NewTransactionModal
        isOpen={isNewTrxModalOpen}
        onClose={() => setIsNewTrxModalOpen(false)}
        onSave={handleCreateTransaction}
        servicesList={servicesList}
      />

      <TambahLayanan
        isOpen={isServiceModalOpen}
        initialData={editingService}
        onClose={() => {
          setIsServiceModalOpen(false);
          setEditingService(null);
        }}
        onSaveService={handleSaveService}
        onDeleteService={handleDeleteService}
      />

      <LogoutModal
        isOpen={isLogoutModalOpen}
        onClose={() => setIsLogoutModalOpen(false)}
        onConfirm={handleLogout}
      />

      <Toast
        toast={toast}
        onClose={() => setToast(null)}
      />
    </div>
  );
}